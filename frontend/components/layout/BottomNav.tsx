export default function BottomNav() {
  const path = usePathname();

  return (
    <nav className="bottom-nav">
      {TABS.map(tab => {
        const active = path.startsWith(tab.href);
        return (
          <Link
            key={tab.href}
            href={tab.href}
            className={`nav-item${active ? ' active' : ''}`}
          >
            {tab.icon(active)}
            <span>{tab.label}</span>
          </Link>
        );
      })}
    </nav>
  );
}
