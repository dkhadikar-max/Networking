// Regression test: the admin panel's two "who is live" signals.
//
//   GET /api/admin/users      is_active was a hand-copied re-implementation of isActiveUser(), and a
//                             banned or deleted account kept reading is_active:true (neither a ban nor
//                             anonymizeUser() touches onboarding_stage / email_verified), so a
//                             moderator scanning the column saw "active" for people who cannot log in.
//   GET /api/admin/analytics  `premium` counted raw premium=true rows: a deleted user keeps premium=true
//                             on its anonymized shell, and a lapsed subscriber keeps it until the next
//                             write, so the headline number disagreed with the per-row Premium badge
//                             (which is isPremiumActive: premium AND a NULL or future expiry).
//
// Decisions pinned here: is_active = isActiveUser && !banned && !deleted_at; premium count = the
// isPremiumActive rule restricted to live (non-deleted) accounts. A BANNED premium user is still
// counted (they still hold the entitlement; banning is a moderation state, not a billing one) and a
// NULL premium_expires_at stays perpetual (locked invariant: never revoked by absence of a date).
//
// How it runs (nothing can touch production): the REAL server.js (or $SERVER_JS) against a
// PostgREST-compatible translator over a REAL PostgreSQL (embedded-postgres), empty cwd (no .env),
// whitelisted env. Requires (test-only): npm install --no-save embedded-postgres pg
// Standalone script (repo convention); exit code = number of failed checks.

